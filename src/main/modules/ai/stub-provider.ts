import type { ProviderId } from '@shared/domain'
import { UserError } from '../../errors'
import { DOC_EDIT_MARKER } from './doc-edit'
import type { AiProvider } from './provider'

/**
 * Deterministic provider for end-to-end tests (enabled with QA_HUB_AI_STUB=1). It echoes which codebase it was
 * given so tests can prove the chosen codebase reaches the AI layer, and returns a fixed case for JSON requests.
 */
export function createStubProvider(id: ProviderId): AiProvider {
  return {
    id,
    async checkAvailability() {
      return { id, ok: true, detail: `Stub ${id} provider` }
    },
    async run(request) {
      if (request.instruction.includes(DOC_EDIT_MARKER)) {
        const asked = /^Request: (.*)$/m.exec(request.prompt)?.[1] ?? ''
        if (asked.includes('FAIL')) throw new UserError('Stub failure')
        const text = `Stub edit: ${asked}`
        request.onEvent({ kind: 'delta', text })
        return { text, usage: { model: 'stub', elapsedMs: 1 } }
      }
      if (request.output === 'json') {
        const cases = [
          {
            title: 'Stub generated case',
            summary: 'Generated by the stub provider.',
            previousBehavior: 'Nothing happened.',
            expectedBehavior: 'The stub case is added to the draft.',
            preconditions: ['Stub precondition'],
            steps: [{ detail: 'Open the app', expected: 'The app opens' }]
          }
        ]
        return { text: JSON.stringify({ cases }), usage: { model: 'stub', elapsedMs: 1 } }
      }
      const text = `Stub ${id} answer. Codebase: ${request.codebase ? `${request.codebase.name} (${request.codebase.path})` : 'none'}.`
      request.onEvent({ kind: 'delta', text })
      return { text, usage: { model: 'stub', elapsedMs: 1 } }
    }
  }
}
